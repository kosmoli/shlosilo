#!/usr/bin/env python3
"""Independent oracle for the keystore data plane (Task 6).

Reimplements the keystone3 keystore pipeline from the SOURCE SPEC
(keystone3-firmware src/managers/keystore.c SaveAccountSecret:503-604 and
src/crypto/utils/hash_and_salt.c) with Python's hashlib/hmac + OpenSSL for
AES-256-CBC, and emits golden_vectors.h for the host test to pin against.

The hardware touch-points are deterministic by the shims' contract
(host_shims.h): TrngGet block j = SHA256("shlosilo-host-sim-trng" || le32(j)),
key pieces are password-bound SHA-256s, OTP salt / inner AES piece are fixed.

Run via run.sh (regenerates golden_vectors.h on every test run).
"""
import hashlib
import hmac
import subprocess
import sys

# ---- shared fixtures (mirrored literally in keystore_host_test.c) ----
SALT = bytes(range(0x10, 0x30))          # fake OTP_ADDR_SALT content
OTP_AES_PIECE = bytes(range(0x40, 0x60))  # fake OTP_ADDR_AES_KEY content
PASSWORD = b"keystone-parity-pw"

def secret_entropy():
    return bytes((0xE0 + i) & 0xFF for i in range(32))

def secret_seed():
    return bytes(i for i in range(64))

def secret_ems():
    return bytes((0x70 + i) & 0xFF for i in range(32))

def secret_reserved():
    return bytes((0xA5 + i) & 0xFF for i in range(32))

HASHWITHSALT_IN = bytes((i ^ 0x5A) & 0xFF for i in range(64))

# ---- primitive helpers ----
def sha256(b):
    return hashlib.sha256(b).digest()

def sha512(b):
    return hashlib.sha512(b).digest()

def hmac256(key, msg):
    return hmac.new(key, msg, hashlib.sha256).digest()

def aes256_cbc_encrypt(key, iv16, pt):
    """Encrypt with OpenSSL (independent AES implementation)."""
    out = subprocess.run(
        ["openssl", "enc", "-aes-256-cbc", "-nopad",
         "-K", key.hex(), "-iv", iv16.hex()],
        input=pt, capture_output=True, check=True).stdout
    assert len(out) == len(pt), "openssl ctaes length mismatch"
    return out

# ---- pipeline reimplementation (keystone3 keystore.c:503-604) ----
def sim_pieces():
    # host_shims.c contract: password-bound key pieces
    return sha256(b"shlosilo-host-sim-atecc-piece" + PASSWORD) + \
           sha256(b"shlosilo-host-sim-ds28s60-piece" + PASSWORD)

def hash_with_salt(data, salt_string):
    # hash_and_salt.c HashWithSaltImpl (sha256 branch), fixed OTP salt
    t = hmac256(SALT, data)
    return hmac256(salt_string.encode(), t)

def sim_trng_block0():
    return sha256(b"shlosilo-host-sim-trng" + (0).to_bytes(4, "little"))

def save_pages():
    pieces = sim_pieces()
    h = hash_with_salt(pieces, "combine two pieces")
    d = sha512(h)
    en_key = bytes(a ^ b for a, b in zip(d[:32], OTP_AES_PIECE))  # CombineInnerAesKey
    auth_key = d[32:]
    iv = sim_trng_block0()                       # TrngGet(iv, AES_IV_LEN), 32B
    pt = secret_entropy() + secret_seed() + secret_ems() + secret_reserved()
    ct = aes256_cbc_encrypt(en_key, iv[:16], pt)  # ctaes uses first 16 of IV
    mac = hmac256(auth_key, iv + ct)              # HMAC over ACCOUNT_TOTAL_LEN-HMAC_LEN
    pages = [iv] + [ct[i:i + 32] for i in range(0, 160, 32)] + [mac]
    assert len(pages) == 7
    return pages

# ---- static known-answer checks (standards vectors) ----
# FIPS 180-4 SHA-256/512 of "abc"
assert sha256(b"abc").hex() == \
    "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", "sha256 abc"
assert sha512(b"abc").hex() == \
    "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a" \
    "2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f", "sha512 abc"
# RFC 4231 test case 1 (HMAC-SHA-256)
assert hmac256(b"\x0b" * 20, b"Hi There").hex() == \
    "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7", "rfc4231-1"

def c_array(name, data, ctype="static const unsigned char"):
    body = ", ".join("0x%02x" % b for b in data)
    return "%s %s[%d] = {%s};\n" % (ctype, name, len(data), body)

def main():
    pages = save_pages()
    # self-check: page accounting must match the keystone3 layout
    assert 32 + 32 + 64 + 32 + 32 + 32 == 224

    w = sys.stdout.write
    w("/* GENERATED by oracle_golden.py - independent oracle (hashlib/hmac +\n"
      " * OpenSSL AES-256-CBC). Regenerated by run.sh on every test run.\n"
      " * Do not edit: fixtures live in oracle_golden.py / keystore_host_test.c. */\n"
      "#ifndef GOLDEN_VECTORS_H\n#define GOLDEN_VECTORS_H\n\n")
    w(c_array("GV_SALT", SALT))
    w(c_array("GV_OTP_AES_PIECE", OTP_AES_PIECE))
    w('static const unsigned char GV_PASSWORD[] = "%s";\n' % PASSWORD.decode())
    w(c_array("GV_PIECES", sim_pieces()))
    w(c_array("GV_HASHWITHSALT_IN", HASHWITHSALT_IN))
    w(c_array("GV_HASHWITHSALT_OUT", hash_with_salt(HASHWITHSALT_IN, "combine two pieces")))
    w(c_array("GV_SHA256_ABC", sha256(b"abc")))
    w(c_array("GV_SHA512_ABC", sha512(b"abc")))
    w(c_array("GV_HMAC_RFC4231_1", hmac256(b"\x0b" * 20, b"Hi There")))
    for i, pg in enumerate(pages):
        w(c_array("GV_SAVE_PAGE_%d" % i, pg))
    w("static const unsigned char *GV_SAVE_PAGES[7] = {\n    " +
      ", ".join("GV_SAVE_PAGE_%d" % i for i in range(7)) + "\n};\n")
    w("\n#endif\n")

if __name__ == "__main__":
    main()
