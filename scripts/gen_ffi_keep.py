#!/usr/bin/env python3
"""Generate the FFI keep table for the forgebox staticlib shim.

Why: the shim bundles the core crate into a staticlib. Under LTO, a staticlib
only retains what is *reachable*; `extern "C"` declarations + a #[used] table do
NOT make the core's functions reachable (verified: they come out `U`/undefined),
while a real Rust-path reference does (they come out `T`/defined). So every
entry point must be referenced through its actual Rust path.

Run:  python3 scripts/gen_ffi_keep.py           # rewrite the block
      python3 scripts/gen_ffi_keep.py --check   # exit 1 if stale
"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SHIM = REPO / "flux/forgebox/staticlib/src/lib.rs"
SHIM_MANIFEST = REPO / "flux/forgebox/staticlib/Cargo.toml"
FORMS = REPO / "forms"
# Task 5a: the flux-side keysource QR C glue (flux/keysource) is bundled into
# the same staticlib, so its #[no_mangle] entries need the same LTO
# reachability — scanned and kept in the same table.
KEYSOURCE = REPO / "flux/keysource/src"
MARKER_START = "// ── C-ABI keep-table (generated by scripts/gen_ffi_keep.py) ──"

FUNC_RE = re.compile(r'^\s*pub (?:unsafe )?extern "C" fn (shlosilo_[a-z_0-9]+)')
MOD_HEAD_RE = re.compile(r"\bmod\s+([A-Za-z_][A-Za-z_0-9]*)\s*$")
ATTR_RE = re.compile(r"^\s*#\[(.*)\]")
CFG_IN_ATTR_RE = re.compile(r"^cfg\((.+)\)$")


def module_path(rel: Path, crate: str) -> str:
    """forms/ffi/c_abi.rs -> shlosilo::ffi::c_abi
    flux/keysource/src/keysource/ffi.rs -> shlosilo_flux_keysource::keysource::ffi"""
    parts = list(rel.with_suffix("").parts)
    if parts and parts[-1] == "mod":
        parts = parts[:-1]
    if parts and parts[-1] == "lib":
        parts = parts[:-1]
    if not parts:
        return crate
    return crate + "::" + "::".join(parts)


def strip_strings_and_comments(line: str) -> str:
    """Blank out //-comments and string/char literals so brace counting is safe."""
    out = []
    i, n = 0, len(line)
    while i < n:
        c = line[i]
        if c == "/" and i + 1 < n and line[i + 1] == "/":
            break
        if c == '"':
            j = i + 1
            while j < n:
                if line[j] == "\\":
                    j += 2
                    continue
                if line[j] == '"':
                    break
                j += 1
            i = j + 1
            out.append(" ")
            continue
        if c == "'":  # char literal or lifetime; blank short char literals only
            if i + 2 < n and line[i + 2] == "'":
                i += 3
                out.append(" ")
                continue
            out.append(c)
            i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def module_file(root: Path, parts):
    """The file that holds the module `parts` (empty = the crate root)."""
    if not parts:
        for cand in ("lib.rs", "mod.rs"):
            if (root / cand).is_file():
                return root / cand
        return None
    base = root.joinpath(*parts)
    for cand in (base / "mod.rs", base.with_suffix(".rs")):
        if cand.is_file():
            return cand
    return None


def decl_cfg(path, name: str):
    """The cfg attribute on the `mod <name>;` / `mod <name> {` declaration in `path`."""
    if path is None or not path.is_file():
        return None
    lines = path.read_text().splitlines()
    pat = re.compile(r"^\s*(?:pub(?:\([^)]*\))?\s+)?mod\s+" + re.escape(name) + r"\s*[;{]")
    for i, raw in enumerate(lines):
        if not pat.match(raw):
            continue
        j = i - 1
        while j >= 0:
            s = lines[j].strip()
            if s == "" or s.startswith("//"):
                j -= 1
                continue
            am = ATTR_RE.match(s)
            if am:
                cm = CFG_IN_ATTR_RE.match(am.group(1))
                if cm:
                    return cm.group(1)
                j -= 1
                continue
            break
        return None
    return None


def inherited_cfg(root: Path, crate: str, rel: Path):
    """cfg chain inherited from the `mod` declarations this file hangs under.

    A feature-gated module (`#[cfg(feature = "se")] pub mod se_ffi;`) removes every
    entry point inside it, so its keep-table entries must carry the same gate - the
    table is compiled against the real Rust path, and a path into a cfg'd-out module
    does not resolve. Reading it off the declaration chain keeps source and table in
    step instead of asking the author to repeat the attribute per function.
    """
    parts = module_path(rel, crate).split("::")[1:]  # drop the crate name
    cfgs = []
    for depth in range(len(parts)):
        cfg = decl_cfg(module_file(root, parts[:depth]), parts[depth])
        if cfg:
            cfgs.append(cfg)
    return " && ".join(cfgs) if cfgs else None


def collect():
    entries = []
    for root, crate in ((FORMS, "shlosilo"), (KEYSOURCE, "shlosilo_flux_keysource")):
        entries.extend(collect_root(root, crate))
    return entries


def shim_features() -> set:
    """Feature names the SHIM crate itself declares.

    A keep-table entry is gated with `#[cfg(feature = ..)]` **in the shim**, so only
    the shim's own features can appear there. A cfg read off the core (e.g.
    `#[cfg(feature = "chain-xmr")]` on a core FFI entry, chain axis 2026-11-26) names
    a feature the shim does not have: emitting it verbatim would either drop a symbol
    the C host still uses (the shim always builds the core with that chain) or fail
    the `unexpected_cfgs` lint. Such an entry is unconditional here — the chain set of
    the bundled core is decided by the shim's dependency line, not by a feature of the
    shim.
    """
    text = SHIM_MANIFEST.read_text()
    names = set()
    in_features = False
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("["):
            in_features = line == "[features]"
            continue
        if in_features and "=" in line:
            names.add(line.split("=", 1)[0].strip())
    return names


def shim_local_cfg(cfg):
    """True when every `feature = "x"` inside `cfg` is a feature the shim declares."""
    if not cfg:
        return True
    declared = shim_features()
    return all(f in declared for f in re.findall(r'feature\s*=\s*"([^"]+)"', cfg))


def collect_root(ROOT: Path, crate: str):
    entries = []
    for path in sorted(ROOT.rglob("*.rs")):
        rel = path.relative_to(ROOT)
        lines = path.read_text().splitlines()
        base = module_path(rel, crate)
        file_cfg = inherited_cfg(ROOT, crate, rel)
        # stack of (is_mod, name) for currently open blocks
        stack = []
        stmt = ""  # statement text since the last brace/semicolon boundary
        for i, raw in enumerate(lines):
            line = strip_strings_and_comments(raw)
            m = FUNC_RE.match(raw)  # match on the raw line: stripping blanks "C" in extern "C"
            if m:
                name = m.group(1)
                mods = [nm for is_mod, nm in stack if is_mod]
                full_mod = base + ("::" + "::".join(mods) if mods else "")
                # walk back for attributes (blank/comment/attr lines)
                attrs = []
                j = i - 1
                while j >= 0:
                    s = lines[j].strip()
                    if s == "" or s.startswith("//"):
                        j -= 1
                        continue
                    am = ATTR_RE.match(s)
                    if am:
                        attrs.append(am.group(1))
                        j -= 1
                        continue
                    break
                cfg = None
                for a in attrs:
                    cm = CFG_IN_ATTR_RE.match(a)
                    if cm:
                        cfg = cm.group(1)
                if not (cfg and "test" in cfg):
                    # The file's own module gate and the function's attribute are both
                    # conditions on that entry point existing at all — but only gates
                    # the SHIM can evaluate belong in the shim's table (see
                    # `shim_local_cfg`).
                    local = [c for c in (file_cfg, cfg) if c and shim_local_cfg(c)]
                    combined = " && ".join(local) or None
                    entries.append((name, full_mod, combined))
            # update the block stack for this line
            for c in line:
                if c == "{":
                    mm = MOD_HEAD_RE.search(stmt)
                    if mm:
                        stack.append((True, mm.group(1)))
                    else:
                        stack.append((False, None))
                    stmt = ""
                elif c == "}":
                    if stack:
                        stack.pop()
                    stmt = ""
                elif c == ";":
                    stmt = ""
                else:
                    if len(stmt) < 100:
                        stmt += c
    return entries


def render(entries):
    out = [MARKER_START]
    out.append("// Every entry point is referenced via its real Rust path so LTO")
    out.append("// cannot drop it from the bundled staticlib (extern decls do not")
    out.append("// create reachability; they left every symbol undefined).")
    out.append("")
    out.append("#[repr(transparent)]")
    out.append("struct Addr(*const ());")
    out.append("// SAFETY: the table is immutable and holds only code addresses.")
    out.append("unsafe impl Sync for Addr {}")
    out.append("")
    cfg_groups = {}
    for name, mod, cfg in entries:
        cfg_groups.setdefault(cfg, []).append((name, mod))
    out.append("#[used]")
    # Slice literal (inferred length): cfg-gated entries mean the element count
    # differs per feature set, so a fixed-size array cannot hold the table.
    out.append("static KEEP_FFI: &[Addr] = &[")
    for cfg in sorted(cfg_groups, key=lambda c: (c is not None, c or "")):
        group = cfg_groups[cfg]
        if cfg:
            # One comment per group, then the gate PER ENTRY: an attribute applies to the
            # single item that follows it, so a group-level `#[cfg]` would gate the first
            # Addr and leave the rest ungated (a table that then fails to compile whenever
            # the gate is off).
            out.append(f"    // present only when: cfg({cfg})")
        for name, mod in group:
            if cfg:
                out.append(f"    #[cfg({cfg})]")
            out.append(f"    Addr({mod}::{name} as *const ()),")
    out.append("];")
    out.append("")
    return "\n".join(out)


def main():
    entries = collect()
    block = render(entries)
    text = SHIM.read_text()
    if MARKER_START in text:
        head = text[: text.index(MARKER_START)].rstrip() + "\n\n"
    else:
        head = text.rstrip() + "\n\n"
        head = re.sub(r"\n// ── C-ABI keep-table ──\n.*\Z", "\n", head, flags=re.S)
        head = re.sub(r"\n#\[used\]\nstatic KEEP_FFI.*\Z", "\n", head, flags=re.S)
        head = re.sub(r'\nextern "C" \{\n(?:    fn shlosilo_[a-z_0-9]+\(\);\n)+\}\n', "\n", head)
    new = head + block
    if "--check" in sys.argv:
        if new != text:
            print("FAIL: shim keep-table is stale; run scripts/gen_ffi_keep.py")
            sys.exit(1)
        print("OK: keep-table up to date (%d entries)" % len(entries))
        return
    SHIM.write_text(new)
    print("wrote %d entries:" % len(entries))
    for name, mod, cfg in entries:
        print(f"  {name:32s} {mod}" + (f"  [cfg({cfg})]" if cfg else ""))


if __name__ == "__main__":
    main()
